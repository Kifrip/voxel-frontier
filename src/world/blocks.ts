export interface BlockTextureFaces {
  top: number;
  bottom: number;
  north: number;
  south: number;
  east: number;
  west: number;
}

export interface BlockDef {
  id: BlockId;
  key: string;
  name: string;
  description: string;
  hardness: number; // Base time in seconds to break by hand; -1 for unbreakable
  preferredTool: ToolType;
  minToolTier: number; // 0 = hand/any, 1 = wood, 2 = stone, 3 = iron
  solid: boolean; // Collides with player/creatures
  opaque: boolean; // Culls adjacent solid faces
  transparent: boolean; // Rendered in transparent/alpha mesh pass
  targetable: boolean; // Raycast hits this block for breaking/placing
  replaceable: boolean; // Placing a block can overwrite this (e.g. water, tall grass)
  renderShape: RenderShape;
  lightLevel: number; // 0..15
  dropItemKey: string | null;
  dropCount: number;
  soundCategory: SoundCategory;
  particleColor: string;
  faces: BlockTextureFaces;
}

